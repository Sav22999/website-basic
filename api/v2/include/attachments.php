<?php
/**
 * Sav Account API v2 - attachments (the screenshots attached to the notes).
 *
 * The images can't travel inside the sync snapshot (limited to 1.5 MB as a
 * whole), so every image is a row of its own. The note only keeps the id of
 * the image, the image itself is uploaded and read here.
 *
 *   - every image is encrypted with the DEK of the account, like the notes:
 *     a password change never touches them;
 *   - only raster images (WebP, JPEG, PNG) are accepted, recognised by their
 *     signature and not only by the declared type;
 *   - every account has a quota ($attachments_quota_bytes);
 *   - when the account is deleted, its images are deleted too.
 *
 * Table and quota can be declared in include/credentials.php; the defaults
 * below are used otherwise. Block 14 of install/migration.sql creates the table.
 */

define("ATT_DEFAULT_TABLE", "sav_attachments");
define("ATT_DEFAULT_QUOTA_BYTES", 100 * 1024 * 1024);
define("ATT_MAX_IMAGE_BYTES", 1024 * 1024);          // decoded image: its base64 stays within the 2 MB body
define("ATT_MAX_DELETE_IDS", 200);

function v2_attachments_table()
{
    global $attachments_table;
    return isset($attachments_table) && is_string($attachments_table) && $attachments_table !== "" ? $attachments_table : ATT_DEFAULT_TABLE;
}

function v2_attachments_quota()
{
    global $attachments_quota_bytes;
    return isset($attachments_quota_bytes) && is_int($attachments_quota_bytes) && $attachments_quota_bytes > 0 ? $attachments_quota_bytes : ATT_DEFAULT_QUOTA_BYTES;
}

function v2_attachments_available($c)
{
    return db_has_table($c, v2_attachments_table());
}

/**
 * Ids are generated by the client: letters, digits and dashes only.
 */
function v2_attachment_id_valid($id)
{
    return is_string($id) && preg_match('/^[A-Za-z0-9-]{8,64}$/', $id) === 1;
}

/**
 * The image of a "data:" URL, only when it really is a WebP, JPEG or PNG
 * image of the declared type. Returns array("mime" => ..., "base64" => ..., "size" => ...)
 * or null.
 */
function v2_attachment_parse($data_url)
{
    if (!is_string($data_url) || preg_match('#^data:(image/(?:webp|jpeg|png));base64,([A-Za-z0-9+/]+={0,2})$#', $data_url, $match) !== 1) {
        return null;
    }
    $binary = base64_decode($match[2], true);
    if ($binary === false || strlen($binary) === 0 || strlen($binary) > ATT_MAX_IMAGE_BYTES) {
        return null;
    }

    $signatures = array(
        "image/png" => strncmp($binary, "\x89PNG\r\n\x1a\n", 8) === 0,
        "image/jpeg" => strncmp($binary, "\xFF\xD8\xFF", 3) === 0,
        "image/webp" => strlen($binary) >= 12 && substr($binary, 0, 4) === "RIFF" && substr($binary, 8, 4) === "WEBP",
    );
    if (!$signatures[$match[1]]) {
        return null;
    }

    return array("mime" => $match[1], "base64" => $match[2], "size" => strlen($binary));
}

function v2_attachments_usage($c, $user_id, $service)
{
    $table = v2_attachments_table();
    $row = db_select_one(
        $c,
        "SELECT COUNT(*) AS `count`, COALESCE(SUM(`size`), 0) AS `used` FROM `$table` WHERE `user-id` = ? AND `service` = ?",
        "ss",
        array($user_id, $service)
    );
    return array(
        "used" => $row === null ? 0 : (int)$row["used"],
        "count" => $row === null ? 0 : (int)$row["count"],
        "quota" => v2_attachments_quota(),
    );
}

/**
 * Stores (or replaces) an image. Returns "ok", "quota" when the account would
 * go beyond its quota, or throws when the database refuses the write.
 */
function v2_attachment_store($c, $user_id, $service, $id, $image, $dek)
{
    $table = v2_attachments_table();
    $encrypted = v2_encrypt_with_dek($image["base64"], $dek);

    return db_tx($c, function ($c) use ($table, $user_id, $service, $id, $image, $encrypted) {
        // the rows of the account are locked: two uploads at the same time can't both pass the quota
        $rows = db_select(
            $c,
            "SELECT `id`, `size` FROM `$table` WHERE `user-id` = ? AND `service` = ? FOR UPDATE",
            "ss",
            array($user_id, $service)
        );
        $used = 0;
        foreach ($rows as $row) {
            if ($row["id"] !== $id) {
                $used += (int)$row["size"];
            }
        }
        if ($used + $image["size"] > v2_attachments_quota()) {
            return "quota";
        }

        $now = date("Y-m-d H:i:s");
        $written = db_execute(
            $c,
            "INSERT INTO `$table` (`user-id`, `service`, `id`, `mime`, `size`, `data`, `created-date`) VALUES (?, ?, ?, ?, ?, ?, ?)
             ON DUPLICATE KEY UPDATE `mime` = VALUES(`mime`), `size` = VALUES(`size`), `data` = VALUES(`data`)",
            "ssssiss",
            array($user_id, $service, $id, $image["mime"], $image["size"], $encrypted, $now)
        );
        if ($written < 0) {
            throw new RuntimeException("attachment write failed");
        }
        return "ok";
    });
}

/**
 * The image as a "data:" URL, null when it doesn't exist (or can't be decrypted).
 */
function v2_attachment_read($c, $user_id, $service, $id, $dek)
{
    $table = v2_attachments_table();
    $row = db_select_one(
        $c,
        "SELECT `mime`, `data` FROM `$table` WHERE `user-id` = ? AND `service` = ? AND `id` = ?",
        "sss",
        array($user_id, $service, $id)
    );
    if ($row === null) {
        return null;
    }
    $base64 = v2_decrypt_with_dek($row["data"], $dek);
    if ($base64 === null || $base64 === "") {
        return null;
    }
    return array("mime" => $row["mime"], "data" => "data:" . $row["mime"] . ";base64," . $base64);
}

/**
 * @return int - the number of deleted images, -1 when the database failed
 */
function v2_attachments_delete($c, $user_id, $service, $ids)
{
    if (count($ids) === 0) {
        return 0;
    }
    $table = v2_attachments_table();
    $placeholders = implode(", ", array_fill(0, count($ids), "?"));
    return db_execute(
        $c,
        "DELETE FROM `$table` WHERE `user-id` = ? AND `service` = ? AND `id` IN ($placeholders)",
        "ss" . str_repeat("s", count($ids)),
        array_merge(array($user_id, $service), $ids)
    );
}

/**
 * Every image of the account, of every service (account deletion).
 */
function v2_attachments_delete_user($c, $user_id)
{
    if (!v2_attachments_available($c)) {
        return;
    }
    $table = v2_attachments_table();
    if (db_execute($c, "DELETE FROM `$table` WHERE `user-id` = ?", "s", array($user_id)) < 0) {
        throw new RuntimeException("attachments delete failed");
    }
}

/**
 * The common start of the attachment endpoints: authenticated session, the
 * service and a ready table.
 */
function v2_attachments_begin($c)
{
    $session = v2_require_auth($c);
    $service = req_service();
    if (!v2_attachments_available($c)) {
        // block 14 of install/migration.sql has not been run yet
        api_error(ERR_UNAVAILABLE);
    }
    return array($session, $service);
}

